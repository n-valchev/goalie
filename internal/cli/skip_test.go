func TestSkippedDirectoriesStaySkippedWhenNamedExplicitly(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"vendor/lib/one.go": "package lib\n\n" + sumFunc("One"),
		"vendor/lib/two.go": "package lib\n\n" + sumFunc("Two"),
	})

	tests := [][]string{
		{"vendor"},
		{"vendor/lib"},
		{"vendor/lib/one.go", "vendor/lib/two.go"},
		{filepath.Join(dir, "vendor", "lib")},
	}
	for _, args := range tests {
		t.Run(strings.Join(args, " "), func(t *testing.T) {
			code, stdout, stderr := runGodry(t, dir, args...)
			if code != 0 || stdout != "No Go files found.\n" {
				t.Errorf("exit code = %d, stdout = %q, stderr = %q", code, stdout, stderr)
			}
		})
	}
}

func TestMissingPathInASkippedDirectoryIsStillAnError(t *testing.T) {
	dir := writeTree(t, map[string]string{"a.go": "package a\n"})

	code, _, _ := runGodry(t, dir, "vendor/missing.go")

	if code != 2 {
		t.Errorf("exit code = %d, want 2", code)
	}
}

// A repo checked out under a hidden or vendored folder must still scan.
