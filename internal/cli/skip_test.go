func TestBuildLineThatDoesNotParseIsAnError(t *testing.T) {
	const bad = "//go:build integration &&\n"
	tests := []struct {
		name, path, header, location string
		args                         []string
	}{
		{name: "first line", path: "copy.go", header: bad + "\n", location: "copy.go:1:"},
		{name: "in a folder", path: "pkg/copy.go", header: bad + "\n", location: "pkg/copy.go:1:"},
		{name: "below a comment", path: "copy.go", header: "// Note.\n\n" + bad + "\n", location: "copy.go:3:"},
		{name: "no expression", path: "copy.go", header: "//go:build\n\n", location: "copy.go:1:"},
		{name: "under --warn-only", path: "copy.go", header: bad + "\n", location: "copy.go:1:", args: []string{"--warn-only"}},
		{name: "with --skip-tags", path: "copy.go", header: bad + "\n", location: "copy.go:1:", args: []string{"--skip-tags", "integration"}},
		{name: "test file in the scan", path: "copy_test.go", header: bad + "\n", location: "copy_test.go:1:", args: []string{"--include-tests"}},
		{name: "after a generated header", path: "copy.go", header: "// Code generated by x. DO NOT EDIT.\n\n" + bad + "\n", location: "copy.go:3:"},
		{name: "after an ignore line", path: "copy.go", header: "//go:build ignore\n" + bad + "\n", location: "copy.go:2:"},
		{name: "after a line directive", path: "copy.go", header: "//line template.y:100\n" + bad + "\n", location: "copy.go:2:"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			wantError(t, copyTree(t, test.path, test.header), "godry: "+test.location, test.args...)
		})
	}
}

