package godeps_test

import (
	"io/fs"
	"path/filepath"
	"slices"
	"testing"
)

func wantClasses(t *testing.T, got model, want ...class) {
	t.Helper()
	if !slices.Equal(got.Classes, want) {
		t.Errorf("classes = %+v, want %+v", got.Classes, want)
	}
}

func wantEdges(t *testing.T, got model, want ...edge) {
	t.Helper()
	if !slices.Equal(got.Edges, want) {
		t.Errorf("edges = %+v, want %+v", got.Edges, want)
	}
}

func dependency(from, to string) edge {
	return edge{"example.com/shop/" + from, "example.com/shop/" + to, "dependency"}
}

func TestTestFilesAreLeftOut(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"go.mod":         goMod,
		"a/a.go":         "package a\n",
		"a/a_test.go":    "package a\n\nimport _ \"example.com/shop/b\"\n",
		"b/b.go":         "package b\n",
		"only/x_test.go": "package only\n",
	})
	got := readModel[model](t, dir)
	wantClasses(t, got, class{"example.com/shop/a", "a", "a"}, class{"example.com/shop/b", "b", "b"})
	wantEdges(t, got)
}

func TestOnlyImportsOfScannedClassesMakeEdges(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"go.mod": goMod,
		"a/a.go": "package a\n\nimport (\n\t\"fmt\"\n\t_ \"example.com/other/lib\"\n\t_ \"example.com/shop/gen\"\n\t_ \"example.com/shop/b\"\n)\n\nvar _ = fmt.Sprint\n",
		"b/b.go": "package b\n",
		// A generated file is never scanned, so this folder holds no class.
		"gen/gen.go": "// Code generated by x. DO NOT EDIT.\n\npackage gen\n",
	})
	wantEdges(t, readModel[model](t, dir), dependency("a", "b"))
}

func TestEveryImportFormMakesOneEdge(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"go.mod":  goMod,
		"a/a.go":  "package a\n\nimport (\n\tnamed \"example.com/shop/b\"\n\t. \"example.com/shop/c\"\n\t_ \"example.com/shop/d\"\n)\n\nvar _ = named.X + Y\n",
		"a/a2.go": "package a\n\nimport \"example.com/shop/b\"\n\nvar _ = b.X\n",
		"b/b.go":  "package b\n\nvar X = 1\n",
		"c/c.go":  "package c\n\nvar Y = 1\n",
		"d/d.go":  "package d\n",
	})
	wantEdges(t, readModel[model](t, dir), dependency("a", "b"), dependency("a", "c"), dependency("a", "d"))
}

func TestEdgesAreSortedByTargetWhateverTheImportOrder(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"go.mod": goMod,
		"a/1.go": "package a\n\nimport _ \"example.com/shop/c\"\n",
		"a/2.go": "package a\n\nimport _ \"example.com/shop/b\"\n",
		"b/b.go": "package b\n",
		"c/c.go": "package c\n",
	})
	wantEdges(t, readModel[model](t, dir), dependency("a", "b"), dependency("a", "c"))
}

func TestAClassAtTheRootHasTheModuleAsItsID(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"go.mod":  goMod,
		"shop.go": "package shop\n",
		"a/a.go":  "package a\n\nimport _ \"example.com/shop\"\n",
	})
	got := readModel[model](t, dir)
	wantClasses(t, got, class{"example.com/shop", "shop", "."}, class{"example.com/shop/a", "a", "a"})
	wantEdges(t, got, edge{"example.com/shop/a", "example.com/shop", "dependency"})
}

func TestTheNameOfAClassIsItsPackageClauseNotItsFolder(t *testing.T) {
	dir := writeTree(t, map[string]string{"go.mod": goMod, "go-thing/a.go": "package thing\n"})
	wantClasses(t, readModel[model](t, dir), class{"example.com/shop/go-thing", "thing", "go-thing"})
}

func TestAFolderWithTwoPackageClausesIsOneClass(t *testing.T) {
	tool := "//go:build tools\n\npackage main\n\nimport _ \"example.com/shop/a\"\n"
	tests := []struct{ name, toolFile string }{
		{"main sorts first", "a/a0.go"},
		{"main sorts last", "a/z.go"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			dir := writeTree(t, map[string]string{"go.mod": goMod, "a/a.go": "package lib\n", test.toolFile: tool})
			got := readModel[model](t, dir)
			wantClasses(t, got, class{"example.com/shop/a", "lib", "a"})
			// The tool imports the library next to it, which is one class importing itself.
			wantEdges(t, got)
		})
	}
}

func TestAFolderWithOnlyMainIsNamedMain(t *testing.T) {
	dir := writeTree(t, map[string]string{"go.mod": goMod, "cmd/x/main.go": "package main\n"})
	wantClasses(t, readModel[model](t, dir), class{"example.com/shop/cmd/x", "main", "cmd/x"})
}

func TestARepoWithNoGoFilesGivesEmptyLists(t *testing.T) {
	dir := writeTree(t, map[string]string{"go.mod": goMod})
	stdout, _ := run(t, dir, 0, "--format", "json")
	want := "{\n  \"version\": 1,\n  \"title\": \"example.com/shop\",\n  \"module\": \"example.com/shop\",\n  \"packages\": [],\n  \"classes\": [],\n  \"edges\": []\n}\n"
	if stdout != want {
		t.Errorf("stdout = %s\nwant %s", stdout, want)
	}
}

func TestTheSameInputGivesTheSameBytes(t *testing.T) {
	tree := map[string]string{"go.mod": goMod}
	for _, name := range []string{"a", "b", "c", "d", "e", "f", "g", "h"} {
		tree[name+"/x.go"] = "package " + name + "\n\nimport (\n\t_ \"example.com/shop/a\"\n\t_ \"example.com/shop/h\"\n)\n"
	}
	dir := writeTree(t, tree)
	first, _ := run(t, dir, 0, "--format", "json")
	for range 20 {
		if again, _ := run(t, dir, 0, "--format", "json"); again != first {
			t.Fatalf("output changed:\n%s\nthen\n%s", first, again)
		}
	}
}

func TestARunCreatesNoFiles(t *testing.T) {
	dir := writeTree(t, map[string]string{"go.mod": goMod, "a/a.go": "package a\n"})
	before := listFiles(t, dir)
	run(t, dir, 0, "--format", "json")
	if after := listFiles(t, dir); !slices.Equal(before, after) {
		t.Errorf("files = %q, want %q", after, before)
	}
}

func listFiles(t *testing.T, dir string) []string {
	t.Helper()
	var names []string
	err := filepath.WalkDir(dir, func(file string, _ fs.DirEntry, err error) error {
		names = append(names, file)
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	return names
}
