package goalie_test

import (
	"encoding/json"
	"strings"
	"testing"
)

func crapSharedTree(t *testing.T, config string) string {
	t.Helper()
	return writeTree(t, map[string]string{
		"go.mod":       goMod,
		"pkg/a.go":     smallFile,
		"billing/b.go": smallFile,
		"p.out":        "mode: set\n",
		".goalierc":    config,
	})
}

func TestWithoutASharedLimitSharedCodeUsesTheLimit(t *testing.T) {
	dir := crapSharedTree(t, `{"shared": ["pkg/**"], "rules": {"crap": {"limit": 5, "coverProfiles": ["p.out"]}}}`)
	stdout, _ := runCrap(t, dir, 1)
	wantStdout(t, stdout, "billing/b.go:3: fail crap: Small scores 6.0 (complexity 2, coverage 0.0%, limit 5)\n"+
		"pkg/a.go:3: fail crap: Small scores 6.0 (complexity 2, coverage 0.0%, limit 5)\n")
}

func TestASharedLimitFlagReplacesTheFile(t *testing.T) {
	dir := crapSharedTree(t, `{"shared": ["pkg/**"], "rules": {"crap": {"sharedLimit": 5, "coverProfiles": ["p.out"]}}}`)
	runCrap(t, dir, 0, "--shared-limit", "6")
}

func TestASharedLimitWithoutSharedCodeIsAnError(t *testing.T) {
	dir := crapSharedTree(t, `{"rules": {"crap": {"sharedLimit": 5, "coverProfiles": ["p.out"]}}}`)
	_, stderr := runCrap(t, dir, 2)
	if !strings.Contains(stderr, "shared") {
		t.Errorf("stderr = %q; want the setting named", stderr)
	}
}

func TestRepoSettingsApply(t *testing.T) {
	tests := []struct {
		name, config string
		want         int
	}{
		{"paths", `{"paths": ["empty"], "rules": {"crap": {"limit": 5, "coverProfiles": ["p.out"]}}}`, 0},
		{"skipFiles", `{"skipFiles": ["a.go"], "rules": {"crap": {"limit": 5, "coverProfiles": ["p.out"]}}}`, 0},
		{"mode", `{"rules": {"crap": {"limit": 5, "mode": "warn", "coverProfiles": ["p.out"]}}}`, 0},
		{"no settings", `{"rules": {"crap": {"limit": 5, "coverProfiles": ["p.out"]}}}`, 1},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			dir := writeTree(t, map[string]string{
				"go.mod":      goMod,
				"a.go":        smallFile,
				"empty/x.txt": "",
				"p.out":       "mode: set\n",
				".goalierc":   test.config,
			})
			runCrap(t, dir, test.want)
		})
	}
}

