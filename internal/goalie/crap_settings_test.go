func TestTheIgnoreCommentSkipsAFunction(t *testing.T) {
	source := "package m\n\n//goalie:ignore crap generated by hand\nfunc Skipped() {}\n\n//goalie:ignore dup a reason for the other rule\nfunc Kept() {}\n"
	dir := writeTree(t, map[string]string{"go.mod": goMod, "a.go": source, "p.out": "mode: set\n"})
	stdout, _ := runCrapWith(t, dir, 1, `"coverProfiles": ["p.out"]`, "--limit", "0")
	wantStdout(t, stdout, "a.go:7: fail crap: Kept scores 2.0 (complexity 1, coverage 0.0%, limit 0)\n")
}

