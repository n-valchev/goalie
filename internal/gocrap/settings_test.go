func TestBadSettingsAreErrors(t *testing.T) {
	tests := []struct {
		name, config string
		args         []string
	}{
		{"negative limit", `{"gocrap": {"limit": -1}}`, nil},
		{"negative shared limit", `{"shared": ["a.go"], "gocrap": {"sharedLimit": -1}}`, nil},
		{"bad format", `{"gocrap": {"format": "xml"}}`, nil},
		{"empty base", `{"gocrap": {"base": ""}}`, nil},
		{"unknown godry setting", `{"godry": {"limits": 1}}`, nil},
		{"negative limit flag", `{}`, []string{"--limit", "-1"}},
		{"bad shared limit flag", `{}`, []string{"--shared-limit", "x"}},
		{"empty base flag", `{}`, []string{"--base", ""}},
		{"unknown flag", `{}`, []string{"--oops"}},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			dir := writeTree(t, map[string]string{
				"go.mod": goMod, "a.go": smallFile, "p.out": "mode: set\n", ".goalierc": test.config,
			})
			run(t, dir, 2, append(test.args, "--cover-profiles", "p.out", "--warn-only")...)
		})
	}
}

