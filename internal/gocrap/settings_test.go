func TestJSONReport(t *testing.T) {
	dir := writeTree(t, map[string]string{"go.mod": goMod, "a.go": decideFile, "p.out": halfCovered})
	stdout, _ := run(t, dir, 1, "--cover-profiles", "p.out", "--limit", "10", "--format", "json")
	var report struct {
		Findings []struct {
			File       string  `json:"file"`
			Line       int     `json:"line"`
			Function   string  `json:"function"`
			Score      float64 `json:"score"`
			Complexity int     `json:"complexity"`
			Coverage   float64 `json:"coverage"`
			Limit      float64 `json:"limit"`
		} `json:"findings"`
	}
	if err := json.Unmarshal([]byte(stdout), &report); err != nil || len(report.Findings) != 1 {
		t.Fatalf("stdout = %q, err = %v; want one finding", stdout, err)
	}
	found := report.Findings[0]
	if found.File != "a.go" || found.Line != 3 || found.Function != "Decide" || found.Score != 10.5 ||
		found.Complexity != 6 || found.Coverage != 0.5 || found.Limit != 10 {
		t.Errorf("finding = %+v", found)
	}
}

func TestJSONIsParsableWhenThereIsNothingToScore(t *testing.T) {
	dir := writeTree(t, map[string]string{"go.mod": goMod})
	stdout, _ := run(t, dir, 0, "--format", "json")
	if strings.ReplaceAll(strings.Join(strings.Fields(stdout), ""), " ", "") != `{"findings":[]}` {
		t.Errorf("stdout = %q; want an empty findings list", stdout)
	}
}

func gitRepo(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := writeTree(t, files)
	git(t, dir, "init", "--initial-branch=main")
	git(t, dir, "add", "--all")
	git(t, dir, "commit", "--message", "first")
	return dir
}

func git(t *testing.T, dir string, args ...string) {
	t.Helper()
	command := exec.Command("git", append([]string{"-c", "user.name=t", "-c", "user.email=t@example.com"}, args...)...)
	command.Dir = dir
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, output)
	}
}

func TestNewCodeModeScoresOnlyChangedFunctions(t *testing.T) {
	dir := gitRepo(t, map[string]string{"go.mod": goMod, "old.go": decideFile, "p.out": "mode: set\n"})
	write(t, dir, "new.go", smallFile)
	stdout, _ := run(t, dir, 1, "--base", "HEAD", "--cover-profiles", "p.out", "--limit", "5")
	wantStdout(t, stdout, "new.go:3: Small scores 6.0 (complexity 2, coverage 0.0%, limit 5)\n")
}

func TestNewCodeModeUsesCoverageFromTheWholeProfile(t *testing.T) {
	dir := gitRepo(t, map[string]string{"go.mod": goMod, "a.go": "package m\n", "p.out": "mode: set\n"})
	write(t, dir, "a.go", decideFile)
	write(t, dir, "p.out", halfCovered)
	stdout, _ := run(t, dir, 1, "--base", "HEAD", "--cover-profiles", "p.out", "--limit", "10")
	wantStdout(t, stdout, "a.go:3: Decide scores 10.5 (complexity 6, coverage 50.0%, limit 10)\n")
}

func TestNewCodeModeWithNoChangedFunctionsRunsNoTests(t *testing.T) {
	dir := gitRepo(t, map[string]string{
		"go.mod":    goMod,
		"a.go":      smallFile,
		".goalierc": `{"gocrap": {"base": "HEAD", "coverCommand": "exit 3"}}`,
	})
	stdout, _ := run(t, dir, 0)
	wantStdout(t, stdout, "No new functions found.\n")
}
