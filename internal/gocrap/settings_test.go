const smallFile = "package m\n\nfunc Small(a int) int {\n\tif a > 0 {\n\t\treturn 1\n\t}\n\treturn 0\n}\n"

func sharedTree(t *testing.T, config string) string {
	t.Helper()
	return writeTree(t, map[string]string{
		"go.mod":       goMod,
		"pkg/a.go":     smallFile,
		"billing/b.go": smallFile,
		"p.out":        "mode: set\n",
		".goalierc":    config,
	})
}

func TestTheSharedLimitAppliesOnlyToSharedCode(t *testing.T) {
	dir := sharedTree(t, `{"shared": ["pkg/**"], "gocrap": {"limit": 30, "sharedLimit": 5, "coverProfiles": ["p.out"]}}`)
	stdout, _ := run(t, dir, 1)
	wantStdout(t, stdout, "pkg/a.go:3: Small scores 6.0 (complexity 2, coverage 0.0%, limit 5)\n")
}

func TestWithoutASharedLimitSharedCodeUsesTheLimit(t *testing.T) {
	dir := sharedTree(t, `{"shared": ["pkg/**"], "gocrap": {"limit": 5, "coverProfiles": ["p.out"]}}`)
	stdout, _ := run(t, dir, 1)
	wantStdout(t, stdout, "billing/b.go:3: Small scores 6.0 (complexity 2, coverage 0.0%, limit 5)\n"+
		"pkg/a.go:3: Small scores 6.0 (complexity 2, coverage 0.0%, limit 5)\n")
}

func TestASharedLimitFlagReplacesTheFile(t *testing.T) {
	dir := sharedTree(t, `{"shared": ["pkg/**"], "gocrap": {"sharedLimit": 5, "coverProfiles": ["p.out"]}}`)
	run(t, dir, 0, "--shared-limit", "6")
}

func TestASharedLimitWithoutSharedCodeIsAnError(t *testing.T) {
	dir := sharedTree(t, `{"gocrap": {"sharedLimit": 5, "coverProfiles": ["p.out"]}}`)
	_, stderr := run(t, dir, 2)
	if !strings.Contains(stderr, "shared") {
		t.Errorf("stderr = %q; want the setting named", stderr)
	}
}

func TestRepoSettingsApply(t *testing.T) {
	tests := []struct {
		name, config string
		want         int
	}{
		{"paths", `{"paths": ["empty"], "gocrap": {"limit": 5}}`, 0},
		{"skipFiles", `{"skipFiles": ["a.go"], "gocrap": {"limit": 5}}`, 0},
		{"warnOnly", `{"gocrap": {"limit": 5, "warnOnly": true}}`, 0},
		{"no settings", `{"gocrap": {"limit": 5}}`, 1},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			dir := writeTree(t, map[string]string{
				"go.mod":      goMod,
				"a.go":        smallFile,
				"empty/x.txt": "",
				"p.out":       "mode: set\n",
				".goalierc":   test.config,
			})
			run(t, dir, test.want, "--cover-profiles", "p.out")
		})
	}
}

